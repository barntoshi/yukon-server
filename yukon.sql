ALTER TABLE auth_tokens
  ADD CONSTRAINT auth_tokens_user FOREIGN KEY ("userId") REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE bans
  ADD CONSTRAINT bans_user FOREIGN KEY ("userId") REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
  ADD CONSTRAINT bans_moderator FOREIGN KEY ("moderatorId") REFERENCES users(id) ON DELETE SET NULL ON UPDATE SET NULL;
ALTER TABLE buddies
  ADD CONSTRAINT buddies_user FOREIGN KEY ("userId") REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
  ADD CONSTRAINT buddies_buddy FOREIGN KEY ("buddyId") REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE cards
  ADD CONSTRAINT cards_user FOREIGN KEY ("userId") REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE furnitures
  ADD CONSTRAINT furnitures_user FOREIGN KEY ("userId") REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE furniture_inventories
  ADD CONSTRAINT furniture_inventories_user FOREIGN KEY ("userId") REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE igloos
  ADD CONSTRAINT igloos_user FOREIGN KEY ("userId") REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE igloo_inventories
  ADD CONSTRAINT igloo_inventories_user FOREIGN KEY ("userId") REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE ignores
  ADD CONSTRAINT ignores_user FOREIGN KEY ("userId") REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
  ADD CONSTRAINT ignores_ignore FOREIGN KEY ("ignoreId") REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE inventories
  ADD CONSTRAINT inventories_user FOREIGN KEY ("userId") REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE pets
  ADD CONSTRAINT pets_user FOREIGN KEY ("userId") REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
  ADD CONSTRAINT pets_feedpostcard FOREIGN KEY ("feedPostcardId") REFERENCES postcards(id) ON DELETE SET NULL ON UPDATE CASCADE;
ALTER TABLE postcards
  ADD CONSTRAINT postcards_user FOREIGN KEY ("userId") REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
  ADD CONSTRAINT postcards_sender FOREIGN KEY ("senderId") REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE;

CREATE OR REPLACE FUNCTION trigger_users_insert() RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO igloos ("userId") VALUES (NEW.id);
    INSERT INTO inventories ("userId", "itemId") VALUES (NEW.id, NEW.color);
    INSERT INTO postcards ("userId", "postcardId") VALUES (NEW.id, 125);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_users_insert
AFTER INSERT ON users
FOR EACH ROW EXECUTE PROCEDURE trigger_users_insert();

COMMIT;
